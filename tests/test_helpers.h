static inline uint32_t rrr(int op2, int op1, int r, int s, int t) {
    return (uint32_t)((op2 << 20) | (op1 << 16) | (r << 12) | (s << 8) | (t << 4) | 0);
}

static inline uint16_t narrow(int op0, int r, int s, int t) {
    return (uint16_t)((r << 12) | (s << 8) | (t << 4) | op0);
}

